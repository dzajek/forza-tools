DROP TABLE IF EXISTS TUNE;

CREATE TABLE TUNE
(
    ID              INTEGER PRIMARY KEY AUTOINCREMENT,
    CAR_ID          INTEGER NOT NULL REFERENCES CAR(ID),
    CAR_CLASS_ID    INTEGER NOT NULL REFERENCES CAR_CLASS(ID),
    TIRES_ID        INTEGER NOT NULL REFERENCES TIRES(ID),
    SUSPENSION_ID   INTEGER NOT NULL REFERENCES SUSPENSION(ID),
    DRIVETRAIN_ID   INTEGER NOT NULL REFERENCES DRIVETRAIN(ID),
    GEARBOX_ID      INTEGER NOT NULL REFERENCES GEARBOX(ID),
    FRONT_AERO_ID   INTEGER NOT NULL REFERENCES AERO(ID),
    REAR_AERO_ID    INTEGER NOT NULL REFERENCES AERO(ID),
    ENGINE          TEXT NOT NULL,
    PI              INTEGER NOT NULL,
    WEIGHT          INTEGER NOT NULL,
    POWER           INTEGER NOT NULL,
    TORQUE          INTEGER NOT NULL,
    LATERAL_GRIP    REAL NOT NULL,
    IS_DEFAULT      BOOLEAN
);